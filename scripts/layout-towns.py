# Uphill paths become stone steps: (town, columns, first row, last row).
STEPS = {
    'town2': [((16, 17), 16, 20), ((26, 27), 16, 20)],
    'town4': [((22, 23), 19, 26)],
    'town5': [((7, 8), 13, 21), ((34, 35), 13, 21)],
    'town7': [((20, 21), 6, 11), ((33, 34), 20, 22)],
}

src = pathlib.Path(__file__).resolve().parent.parent / 'dist' / 'maps.js'
text = src.read_text()

def art_block(tid):
    m = re.search(r"id: '%s'.*?art: \[\n(.*?)\n  \],\n" % tid, text, re.S)
    return m

for tid, rows in TOWNS.items():
    assert len(rows) == 30, (tid, len(rows))
    for i, r in enumerate(rows): assert len(r) == 42, (tid, i, len(r), r)
    m = art_block(tid)
    body = ',\n'.join("   '%s'" % r for r in rows)
    text = text[:m.start(1)] + body + text[m.end(1):]

for tid, runs in STEPS.items():
    m = art_block(tid)
    rows = [l.strip().strip(',').strip("'") for l in m.group(1).split('\n')]
    for cols, y0, y1 in runs:
        for y in range(y0, y1 + 1):
            r = list(rows[y])
            for x in cols:
                if r[x] == '=': r[x] = '^'
            rows[y] = ''.join(r)
    body = ',\n'.join("   '%s'" % r for r in rows)
    text = text[:m.start(1)] + body + text[m.end(1):]

src.write_text(text)
print('rewrote', ', '.join(TOWNS), '+ steps in', ', '.join(STEPS))

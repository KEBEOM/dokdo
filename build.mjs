// Rebuild both double-click entry points after editing the JavaScript sources.
// Run: node build.mjs
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.dirname(fileURLToPath(import.meta.url));
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const write=(name,body)=>fs.writeFileSync(path.join(root,name),body);
const playerSheets={};
for(const id of ['girl','boy'])playerSheets['characters/'+id+'-sheet']='data:image/png;base64,'+fs.readFileSync(path.join(root,'assets/characters/'+id+'-sheet.png')).toString('base64');
write('player-art.js','// Original uploaded sheets. Generated by build.mjs.\nexport const PLAYER_SHEETS='+JSON.stringify(playerSheets)+';\n');
const parts=["(()=>{'use strict';const __modules=Object.create(null);"];
for(const name of ['data.js','learning.js','engine.js','player-art.js','assets.js','sprites.js','characters.js','world.js','battle-quiz.js','game.js']){
  let code=read(name);
  const exports=[...code.matchAll(/export\s+(?:const|let|function|class)\s+(\w+)/g)].map(m=>m[1]);
  code=code.replace(/import\s*\{([^}]+)\}\s*from\s*'\.\/([^']+)';/g,(_,names,file)=>`const {${names}}=__modules[${JSON.stringify(file)}];`);
  code=code.replace(/\bexport\s+(?=(?:const|let|function|class)\b)/g,'');
  parts.push(`__modules[${JSON.stringify(name)}]=(()=>{\n${code}\nreturn {${exports.join(',')}};\n})();`);
}
parts.push('})();');
const bundle=parts.join('\n');
write('game.bundle.js',bundle);
let index=read('index.html').replace('<script type="module" src="game.js"></script>','<script src="game.bundle.js"></script>');
write('index.html',index);
const embedded={};
function scan(dir,prefix=''){for(const entry of fs.readdirSync(dir,{withFileTypes:true})){const file=path.join(dir,entry.name),key=prefix+entry.name;if(entry.isDirectory())scan(file,key+'/');else if(entry.name.endsWith('.png')&&entry.name!=='monster-contact-sheet.png')embedded[key.slice(0,-4)]='data:image/png;base64,'+fs.readFileSync(file).toString('base64');}}
scan(path.join(root,'assets'));
const assetScript='globalThis.DOKDOMON_EMBEDDED_ASSETS='+JSON.stringify(embedded)+';';
const standalone=index.replace('<link rel="stylesheet" href="style.css">',()=>'<style>'+read('style.css')+'</style>')
  .replace('<script src="game.bundle.js"></script>',()=>'<script>'+assetScript+'\n'+bundle.replace(/<\/script/gi,'<\\/script')+'</script>');
write('dokdo-explorers.html',standalone);
console.log('Built game.bundle.js and dokdo-explorers.html. Open index.html in Chrome or Edge.');
